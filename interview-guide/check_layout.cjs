const {chromium}=require('C:/Users/rk751/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const path=require('path');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 await page.goto('file:///'+path.join(__dirname,'RAG_Interview_Guide.html').replaceAll('\\','/'));
 await page.screenshot({path:path.join(__dirname,'layout-desktop.png')});
 const count=await page.locator('article.question').count();
 if(count!==110)throw new Error('Question count');
 await page.locator('#search').fill('MCP');
 const matches=await page.locator('article.question:visible').count();
 if(!(matches>0 && matches<110))throw new Error('Search');
 await page.locator('#search').fill('');
 await page.locator('#practice').click();
 if(await page.locator('#q1 p').first().isVisible())throw new Error('Practice mode');
 await page.locator('#practice').click();
 if(!await page.locator('#q1 p').first().isVisible())throw new Error('Answer mode');
 const anchors=await page.evaluate(()=>[...document.querySelectorAll('a[href^="#"]')].filter(a=>!document.getElementById(a.hash.slice(1))).map(a=>a.hash));
 if(anchors.length)throw new Error('Missing anchors '+anchors);
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow)throw new Error('Desktop overflow');
 await page.locator('#q77').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(__dirname,'layout-code.png')});
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>scrollTo(0,0));
 await page.screenshot({path:path.join(__dirname,'layout-mobile.png')});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Mobile overflow');
 console.log(JSON.stringify({questions:count,searchMatches:matches,anchors:'passed',practice:'passed',desktop:'passed',mobile:'passed'}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
